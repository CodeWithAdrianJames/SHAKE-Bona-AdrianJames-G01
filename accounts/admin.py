from django.contrib import admin
from django.contrib.auth.admin import UserAdmin

from .models import APIToken, CustomUser


@admin.register(CustomUser)
class CustomUserAdmin(UserAdmin):
    list_display = [
        "username",
        "email",
        "first_name",
        "last_name",
        "role",
        "department",
        "is_staff",
        "is_active",
    ]
    list_filter = ["role", "department", "is_staff", "is_superuser", "is_active"]
    search_fields = ["username", "first_name", "last_name", "email", "department"]
    ordering = ["-date_joined"]

    fieldsets = UserAdmin.fieldsets + (
        (
            "SHAKE Operational Profile",
            {
                "fields": (
                    "role",
                    "department",
                    "contact_number",
                    "profile_photo",
                )
            },
        ),
    )
    add_fieldsets = UserAdmin.add_fieldsets + (
        (
            "SHAKE Operational Profile",
            {
                "fields": (
                    "email",
                    "first_name",
                    "last_name",
                    "role",
                    "department",
                    "contact_number",
                    "profile_photo",
                )
            },
        ),
    )


@admin.register(APIToken)
class APITokenAdmin(admin.ModelAdmin):
    """Audit and revoke local loopback API tokens (F-11). Raw keys are never displayed."""

    list_display = ["name", "user", "masked_key", "is_active", "created_at", "last_used_at"]
    list_filter = ["is_active"]
    search_fields = ["name", "user__username", "user__email"]
    fields = ["user", "name", "is_active", "masked_key", "created_at", "last_used_at"]
    readonly_fields = ["user", "masked_key", "created_at", "last_used_at"]

    def has_add_permission(self, request):
        # Tokens are generated by their owner on /accounts/profile/.
        return False
